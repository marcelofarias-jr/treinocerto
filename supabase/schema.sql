-- Tabela de treinos
CREATE TABLE IF NOT EXISTS workouts (
  id BIGINT PRIMARY KEY,
  user_email TEXT NOT NULL,
  format TEXT NOT NULL,
  days JSONB NOT NULL DEFAULT '[]',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_workouts_user_email ON workouts(user_email);

-- Tabela de sessões de treino
CREATE TABLE IF NOT EXISTS sessions (
  id BIGINT PRIMARY KEY,
  user_email TEXT NOT NULL,
  date TEXT NOT NULL,
  workout_id BIGINT,
  day_id TEXT,
  day_label TEXT,
  duration INT DEFAULT 0,
  exercises_data JSONB DEFAULT '[]',
  notes TEXT DEFAULT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Migração: adicionar coluna notes em bases existentes
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS notes TEXT DEFAULT NULL;

CREATE INDEX IF NOT EXISTS idx_sessions_user_email ON sessions(user_email);
CREATE INDEX IF NOT EXISTS idx_sessions_date ON sessions(user_email, date);

-- Exercícios customizados pelo usuário
CREATE TABLE IF NOT EXISTS custom_exercises (
  id BIGINT PRIMARY KEY,
  user_email TEXT NOT NULL,
  muscle_group TEXT NOT NULL,
  name TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_custom_exercises_user ON custom_exercises(user_email);

-- Migração: marca qual treino do usuário é o ativo (executado por padrão).
-- No máximo um ativo por usuário; garantido pela API ao definir o ativo.
ALTER TABLE workouts ADD COLUMN IF NOT EXISTS is_active BOOLEAN DEFAULT false;

-- Migração: quando o treino passou a ser o ativo, para exibir "ativo há X".
-- Nulo em treinos ativados antes desta coluna existir: a UI cai para created_at.
ALTER TABLE workouts ADD COLUMN IF NOT EXISTS activated_at TIMESTAMPTZ;

-- Exercícios padrão ocultos (excluídos ou substituídos pelo admin)
CREATE TABLE IF NOT EXISTS hidden_exercises (
  name TEXT PRIMARY KEY,
  muscle_group TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Registro de suplementos tomados por dia (a existência da linha = tomado)
CREATE TABLE IF NOT EXISTS supplement_logs (
  id BIGINT PRIMARY KEY,
  user_email TEXT NOT NULL,
  date TEXT NOT NULL,
  name TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_supplement_logs_unique ON supplement_logs(user_email, date, name);
CREATE INDEX IF NOT EXISTS idx_supplement_logs_user_date ON supplement_logs(user_email, date);

-- Peso corporal por dia (um registro por usuário/data; a API faz upsert).
-- Estava só no banco, sem constar aqui — recriar o schema deste arquivo
-- deixava a tela de estatísticas quebrada.
CREATE TABLE IF NOT EXISTS body_weight (
  id BIGINT PRIMARY KEY,
  user_email TEXT NOT NULL,
  date TEXT NOT NULL,
  weight NUMERIC NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_body_weight_unique ON body_weight(user_email, date);
CREATE INDEX IF NOT EXISTS idx_body_weight_user ON body_weight(user_email);

-- ─────────────────────────────────────────────────────────────────────────────
-- Migração: ids gerados pelo banco.
--
-- Os ids vinham de Date.now() na aplicação, o que colide quando duas inserções
-- caem no mesmo milissegundo — em supplement_logs, que tem índice único, o erro
-- subia cru para a tela. Ids sequenciais por tempo também são enumeráveis.
--
-- GENERATED BY DEFAULT (e não ALWAYS) mantém a compatibilidade: o banco gera o
-- id quando a aplicação não manda, e aceita id explícito quando manda.
-- Idempotente: rodar de novo só reposiciona as sequências.
-- ─────────────────────────────────────────────────────────────────────────────
DO $$
DECLARE
  t text;
  seq text;
BEGIN
  FOREACH t IN ARRAY ARRAY['workouts', 'sessions', 'custom_exercises', 'body_weight', 'supplement_logs']
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_attribute
      WHERE attrelid = t::regclass AND attname = 'id' AND attidentity <> ''
    ) THEN
      EXECUTE format('ALTER TABLE %I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', t);
    END IF;

    -- Começa acima do maior id existente (os antigos são timestamps de 13 dígitos).
    seq := pg_get_serial_sequence(t, 'id');
    IF seq IS NOT NULL THEN
      EXECUTE format('SELECT setval(%L, COALESCE((SELECT MAX(id) FROM %I), 0) + 1, false)', seq, t);
    END IF;
  END LOOP;
END $$;

-- ─────────────────────────────────────────────────────────────────────────────
-- Constraints de integridade: segunda camada de validação.
-- A API valida a entrada, mas usa a service_role key (que ignora RLS), então
-- vale o banco recusar o que é inválido por definição.
-- ─────────────────────────────────────────────────────────────────────────────
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'body_weight_range') THEN
    ALTER TABLE body_weight ADD CONSTRAINT body_weight_range CHECK (weight >= 20 AND weight <= 400);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'body_weight_date_fmt') THEN
    ALTER TABLE body_weight ADD CONSTRAINT body_weight_date_fmt CHECK (date ~ '^\d{4}-\d{2}-\d{2}$');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'sessions_duration_range') THEN
    ALTER TABLE sessions ADD CONSTRAINT sessions_duration_range CHECK (duration >= 0 AND duration <= 86400);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'sessions_date_fmt') THEN
    ALTER TABLE sessions ADD CONSTRAINT sessions_date_fmt CHECK (date ~ '^\d{4}-\d{2}-\d{2}$');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'supplement_logs_date_fmt') THEN
    ALTER TABLE supplement_logs ADD CONSTRAINT supplement_logs_date_fmt CHECK (date ~ '^\d{4}-\d{2}-\d{2}$');
  END IF;
END $$;
